/**
 * Creates dist/akash-roy-digital-lab.zip from tracked source files only.
 * Excludes dependencies, build output, caches, local media, real .env files,
 * test artefacts and anything matching the private-data rules below.
 *
 *   npm run zip
 */
import { createWriteStream, mkdirSync, readdirSync, readFileSync, statSync } from 'node:fs';
import path from 'node:path';
import { deflateRawSync } from 'node:zlib';

const ROOT = process.cwd();
const OUT_DIR = path.join(ROOT, 'dist');
const OUT = path.join(OUT_DIR, 'akash-roy-digital-lab.zip');
const PREFIX = 'akash-roy-digital-lab/';

export const EXCLUDED_DIRS = new Set([
  'node_modules',
  '.next',
  '.next-dev',
  'dist',
  'out',
  'coverage',
  'playwright-report',
  'test-results',
  'blob-report',
  'storage',
  'storage-test',
  'storage-e2e',
  '.git',
  '.claude',
  '.vercel',
  '.turbo',
]);
export const EXCLUDED_FILE_PATTERNS = [
  /^\.env$/,
  /^\.env\.(?!example$).+/, // real environment files
  /\.log$/,
  /\.tsbuildinfo$/,
  /^next-env\.d\.ts$/,
  /\.dump$/,
  /\.sql\.gz$/,
  /^Thumbs\.db$/,
  /^\.DS_Store$/,
  /^pdf\.worker\.min\.mjs$/, // generated by postinstall
  /\.(pem|key|p12|pfx)$/i,
];

function walk(dir, rel = '') {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const r = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (EXCLUDED_DIRS.has(entry.name)) continue;
      out.push(...walk(path.join(dir, entry.name), r));
    } else if (entry.isFile()) {
      if (EXCLUDED_FILE_PATTERNS.some((re) => re.test(entry.name))) continue;
      out.push(r);
    }
  }
  return out;
}

// CRC-32 (IEEE)
const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function dosTime(d) {
  return {
    time: (d.getHours() << 11) | (d.getMinutes() << 5) | Math.floor(d.getSeconds() / 2),
    date: ((d.getFullYear() - 1980) << 9) | ((d.getMonth() + 1) << 5) | d.getDate(),
  };
}

function main() {
  const files = walk(ROOT).sort();
  mkdirSync(OUT_DIR, { recursive: true });
  const chunks = [];
  const central = [];
  let offset = 0;
  for (const rel of files) {
    const data = readFileSync(path.join(ROOT, rel));
    const name = Buffer.from(PREFIX + rel, 'utf8');
    const compressed = deflateRawSync(data, { level: 9 });
    const useDeflate = compressed.length < data.length;
    const body = useDeflate ? compressed : data;
    const crc = crc32(data);
    const { time, date } = dosTime(statSync(path.join(ROOT, rel)).mtime);
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6); // UTF-8 names
    local.writeUInt16LE(useDeflate ? 8 : 0, 8);
    local.writeUInt16LE(time, 10);
    local.writeUInt16LE(date, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(body.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(name.length, 26);
    local.writeUInt16LE(0, 28);
    chunks.push(local, name, body);
    const cen = Buffer.alloc(46);
    cen.writeUInt32LE(0x02014b50, 0);
    cen.writeUInt16LE(20, 4);
    cen.writeUInt16LE(20, 6);
    cen.writeUInt16LE(0x0800, 8);
    cen.writeUInt16LE(useDeflate ? 8 : 0, 10);
    cen.writeUInt16LE(time, 12);
    cen.writeUInt16LE(date, 14);
    cen.writeUInt32LE(crc, 16);
    cen.writeUInt32LE(body.length, 20);
    cen.writeUInt32LE(data.length, 24);
    cen.writeUInt16LE(name.length, 28);
    cen.writeUInt32LE(offset, 42);
    central.push(cen, name);
    offset += local.length + name.length + body.length;
  }
  const centralBuf = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(files.length, 8);
  end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(centralBuf.length, 12);
  end.writeUInt32LE(offset, 16);
  const stream = createWriteStream(OUT);
  for (const c of chunks) stream.write(c);
  stream.write(centralBuf);
  stream.end(end);
  stream.on('finish', () => {
    console.log(
      `Created ${path.relative(ROOT, OUT)} — ${files.length} files, ${(statSync(OUT).size / 1024).toFixed(0)} KB`,
    );
    console.log('Verify with: npm run zip:verify');
  });
}

main();
